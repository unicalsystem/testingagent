"""Self-contained HTML report of a cross-device mobile run (release 1.8)."""
from __future__ import annotations

import base64
import html as h
from collections import OrderedDict

from sqlalchemy import select

from . import storage
from .models import MobileProvider, MobileRun, MobileRunGroup, Project

COLORS = {"passed": "#15803d", "failed": "#b91c1c", "error": "#b45309", "cancelled": "#6b7280", "queued": "#6b7280",
          "running": "#1d4ed8", "skipped": "#9ca3af"}
MAX_IMAGES = 30


def _badge(st: str) -> str:
    return f'<span class="b" style="background:{COLORS.get(st, "#6b7280")}">{h.escape(st)}</span>'


def _dev(d: dict) -> str:
    return f"{d.get('name', '')} · {d.get('platform', '')} {d.get('os_version', '')}".strip()


def html(db, g: MobileRunGroup, project: Project) -> str:
    runs = db.scalars(select(MobileRun).where(MobileRun.group_id == g.id).order_by(MobileRun.id)).all()
    prov = db.get(MobileProvider, g.provider_id) if g.provider_id else None
    devices = list(OrderedDict.fromkeys(_dev(r.device or {}) for r in runs))
    cases: OrderedDict[str, dict] = OrderedDict()
    for r in runs:
        cases.setdefault((r.case_snapshot or {}).get("name", f"case {r.case_id}"), {})[_dev(r.device or {})] = r
    total = len(runs)
    counts: dict[str, int] = {}
    for r in runs:
        counts[r.status] = counts.get(r.status, 0) + 1
    out = [f"""<!doctype html><html><head><meta charset="utf-8"><title>Mobile run {g.id} — {h.escape(project.name)}</title>
<style>body{{font:14px/1.45 -apple-system,Segoe UI,Roboto,sans-serif;color:#111827;margin:28px;max-width:1200px}}
h1{{font-size:22px;margin:0 0 4px}}h2{{font-size:17px;margin:28px 0 8px}}table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #e5e7eb;padding:6px 8px;text-align:left;vertical-align:top}}th{{background:#f9fafb}}
.b{{color:#fff;border-radius:10px;padding:1px 8px;font-size:12px}}.m{{color:#6b7280}}img{{max-width:260px;border:1px solid #e5e7eb;border-radius:6px}}
.k{{display:inline-block;margin-right:18px}}</style></head><body>
<h1>Mobile test run #{g.id}: {h.escape(g.name)}</h1>
<div class="m">Project {h.escape(project.name)} · {h.escape(prov.name if prov else 'removed provider')} · started {g.created_at:%Y-%m-%d %H:%M} UTC · generated by TestAgent</div>
<p>{''.join(f'<span class="k">{_badge(k)} {v}</span>' for k, v in counts.items())} <span class="k">total {total}</span></p>
<h2>Cross-device matrix</h2><table><tr><th>Case</th>{''.join(f'<th>{h.escape(d)}</th>' for d in devices)}</tr>"""]
    for name, by_dev in cases.items():
        out.append(f"<tr><td>{h.escape(name)}</td>")
        for d in devices:
            r = by_dev.get(d)
            out.append(f'<td>{_badge(r.status)} <a href="#run{r.id}">#{r.id}</a></td>' if r else "<td class=m>—</td>")
        out.append("</tr>")
    out.append("</table>")
    images = 0
    for r in runs:
        snap = r.case_snapshot or {}
        out.append(f'<h2 id="run{r.id}">#{r.id} · {h.escape(snap.get("name", ""))} on {h.escape(_dev(r.device or {}))} {_badge(r.status)}</h2>')
        if r.error:
            out.append(f'<p style="color:#b91c1c">{h.escape(r.error)}</p>')
        if r.session_url:
            out.append(f'<p class="m">Device session (video, logs): {h.escape(r.session_url)}</p>')
        out.append("<table><tr><th>#</th><th>Step</th><th>Result</th><th>Time</th><th>Details</th></tr>")
        for s in r.step_results or []:
            det = h.escape(s.get("error") or s.get("note") or "")
            if s.get("shot") and s.get("status") == "failed" and images < MAX_IMAGES:
                try:
                    data = storage.resolve_evidence(s["shot"]).read_bytes()
                    mime = "image/jpeg" if s["shot"].endswith(".jpg") else "image/png"
                    det += f'<br><img alt="screen" src="data:{mime};base64,{base64.b64encode(data).decode()}">'
                    images += 1
                except (OSError, PermissionError):
                    pass
            out.append(f"<tr><td>{s.get('i', 0) + 1}</td><td>{h.escape(s.get('description', ''))}</td><td>{_badge(s.get('status', ''))}</td>"
                       f"<td>{s.get('ms', 0)} ms</td><td>{det}</td></tr>")
        out.append("</table>")
    out.append("</body></html>")
    return "".join(out)
